import {readFile,writeFile} from 'node:fs/promises';
const folder='public/workspace/vendor/aruco/';
const cv=await readFile(folder+'cv.js','utf8'),aruco=await readFile(folder+'aruco.js','utf8');
// Keep the pinned upstream code and licenses intact; adapt its browser globals to ESM.
await writeFile(folder+'detector.js',`// Generated by scripts/build-marker-runtime.mjs; see LICENSE.txt and UPSTREAM.txt.\nconst scope={};\n(function(){\n${cv}\n${aruco}\n}).call(scope);\nexport const AR=scope.AR;\n`);
const {AR}=await import('../'+folder+'detector.js');
await writeFile('public/workspace/marker.svg',new AR.Dictionary('ARUCO_MIP_36h12').generateSVG(17));
console.log('Pinned marker detector and VisionLink marker 17 prepared.');
